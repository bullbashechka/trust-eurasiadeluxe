export type ApartmentId = "36-67" | "39-87" | "79-79";
export interface Scene {
  id: string;
  room: string;
  caption: string;
  poster: string;
  desktop: string;
  mobile: string;
  duration: number;
}
export interface Apartment {
  id: ApartmentId;
  area: string;
  rooms: number;
  title: string;
  description: string;
  cover: string;
  plan: string;
  features: string[];
  scenes: Scene[];
}
type Shot = [string, string, string, boolean?];
function scenes(id: ApartmentId, shots: Shot[]): Scene[] {
  return shots.map(([number, room, caption, still]) => ({
    id: number,
    room,
    caption,
    poster: `/media/${id}/${number}.webp`,
    desktop: `/media/${id}/${number}-desktop.mp4`,
    mobile: `/media/${id}/${number}-mobile.mp4`,
    duration: still ? 3 : 3.04,
  }));
}
